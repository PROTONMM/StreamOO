#!/usr/bin/env python3
"""Original StreamOO paths -> SVG and OLED alpha4. Host-only: pycairo 1.25.1."""
from pathlib import Path
import cairo

ROOT = Path(__file__).resolve().parents[1]
WIDTH, HEIGHT, SCALE = 224, 40, 4
# Own geometric lettering, not outlines imported from a font. M/L/C only.
LETTERS = [
    [('M', 26, 10), ('C', 20, 3, 5, 5, 5, 14),
     ('C', 5, 23, 26, 17, 26, 27), ('C', 26, 36, 10, 38, 4, 31)],
    [('M', 38, 9), ('L', 38, 28), ('C', 38, 34, 41, 35, 46, 32)],
    [('M', 32, 16), ('L', 46, 16)],
    [('M', 54, 34), ('L', 54, 17), ('M', 54, 23),
     ('C', 57, 17, 61, 16, 65, 17)],
    [('M', 72, 24), ('L', 88, 24), ('C', 88, 12, 71, 12, 71, 25),
     ('C', 71, 35, 81, 38, 87, 32)],
    [('M', 113, 17), ('L', 113, 34), ('M', 113, 25),
     ('C', 113, 13, 96, 13, 96, 25), ('C', 96, 37, 113, 37, 113, 25)],
    [('M', 123, 34), ('L', 123, 17), ('M', 123, 23),
     ('C', 123, 14, 137, 14, 137, 23), ('L', 137, 34), ('M', 137, 23),
     ('C', 137, 14, 151, 14, 151, 23), ('L', 151, 34)],
]
LOOPS = [[('M', 192, 21), ('C', 181, 4, 164, 4, 164, 21),
          ('C', 164, 38, 181, 38, 192, 21),
          ('C', 203, 4, 220, 4, 220, 21),
          ('C', 220, 38, 203, 38, 192, 21)]]


def path_data(paths):
    return ' '.join(' '.join(map(str, command)) for path in paths for command in path)


def main():
    svg = ('<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 224 40" '
           'role="img" aria-label="StreamOO">\n'
           '  <g fill="none" stroke-width="3.5" stroke-linecap="round" '
           'stroke-linejoin="round">\n'
           f'    <path stroke="#182b31" d="{path_data(LETTERS)}"/>\n'
           f'    <path stroke="#2e654b" d="{path_data(LOOPS)}"/>\n'
           '  </g>\n</svg>\n')
    (ROOT / 'assets/branding/streamoo.svg').write_text(svg)
    page = ROOT / 'components/portal/web/index.html'
    before, begin, rest = page.read_text().partition('<!-- StreamOO wordmark: begin -->')
    _, end, after = rest.partition('<!-- StreamOO wordmark: end -->')
    if not begin or not end:
        raise ValueError('Missing wordmark markers in portal HTML')
    inline = svg.strip().replace('<svg ', '<svg class="brand" width="224" height="40" ', 1)
    page.write_text(before + begin + inline + end + after)
    surface = cairo.ImageSurface(cairo.FORMAT_A8, WIDTH * SCALE, HEIGHT * SCALE)
    ctx = cairo.Context(surface)
    ctx.scale(SCALE, SCALE)
    ctx.set_source_rgba(1, 1, 1, 1)
    ctx.set_line_width(3.5)
    ctx.set_line_cap(cairo.LINE_CAP_ROUND)
    ctx.set_line_join(cairo.LINE_JOIN_ROUND)
    for path in LETTERS + LOOPS:
        for op, *coords in path:
            {'M': ctx.move_to, 'L': ctx.line_to, 'C': ctx.curve_to}[op](*coords)
        ctx.stroke()
    surface.flush()
    data, stride = bytes(surface.get_data()), surface.get_stride()
    levels = []
    for y in range(HEIGHT):
        for x in range(WIDTH):
            coverage = sum(data[(y * SCALE + dy) * stride + x * SCALE + dx]
                           for dy in range(SCALE) for dx in range(SCALE))
            levels.append((coverage * 15 + 2040) // 4080)
    packed = [levels[i] * 16 + levels[i + 1] for i in range(0, len(levels), 2)]
    lines = [', '.join(f'0x{v:02x}' for v in packed[i:i + 16])
             for i in range(0, len(packed), 16)]
    header = ('/* Generated by tools/generate_brand_mark.py; original StreamOO paths. */\n'
              'static const uint8_t boot_wordmark[4480] = {\n    ' +
              ',\n    '.join(lines) + '\n};\n')
    (ROOT / 'components/ui/streamoo_boot_wordmark.inc').write_text(header)


if __name__ == '__main__':
    main()
